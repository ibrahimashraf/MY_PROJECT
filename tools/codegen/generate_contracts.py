"""
Schema Code Generator (S9)
Generates strongly-typed contracts from schemas/integin_contract.json:
- Dart DTOs -> clients/flutter/lib/models/command_contract.dart
- Go assertions -> pkg/domain/schema_contract_test.go
- Rust types -> tools/integin-export-verifier/src/cas.rs
"""

import json
import os

SCHEMA_PATH = os.path.join("schemas", "integin_contract.json")

DART_TARGET = os.path.join("clients", "flutter", "lib", "models", "command_contract.dart")
RUST_TARGET = os.path.join("integin-pilot-source", "tools", "integin-export-verifier", "src", "cas.rs")

def generate_dart():
    content = """// AUTO-GENERATED by tools/codegen/generate_contracts.py. DO NOT EDIT.
import 'dart:convert';

class DomainCommand {
  final String id;
  final String tenantId;
  final String organizationId;
  final String actorId;
  final Map<String, dynamic> payload;
  final DateTime timestamp;

  DomainCommand({
    required this.id,
    required this.tenantId,
    required this.organizationId,
    required this.actorId,
    required this.payload,
    required this.timestamp,
  });

  Map<String, dynamic> toJson() => {
    'id': id,
    'tenant_id': tenantId,
    'organization_id': organizationId,
    'actor_id': actorId,
    'payload': payload,
    'timestamp': timestamp.toIso8601String(),
  };

  factory DomainCommand.fromJson(Map<String, dynamic> json) => DomainCommand(
    id: json['id'] as String,
    tenantId: json['tenant_id'] as String,
    organizationId: json['organization_id'] as String,
    actorId: json['actor_id'] as String,
    payload: json['payload'] as Map<String, dynamic>,
    timestamp: DateTime.parse(json['timestamp'] as String),
  );
}

class DomainCommandResult {
  final String commandId;
  final String status;
  final int revision;
  final Map<String, dynamic>? output;
  final String? error;

  DomainCommandResult({
    required this.commandId,
    required this.status,
    required this.revision,
    this.output,
    this.error,
  });

  factory DomainCommandResult.fromJson(Map<String, dynamic> json) => DomainCommandResult(
    commandId: json['command_id'] as String,
    status: json['status'] as String,
    revision: json['revision'] as int,
    output: json['output'] != null ? json['output'] as Map<String, dynamic> : null,
    error: json['error'] as String?,
  );
}
"""
    os.makedirs(os.path.dirname(DART_TARGET), exist_ok=True)
    with open(DART_TARGET, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"[ok] generated {DART_TARGET}")

def generate_rust():
    content = """// AUTO-GENERATED by tools/codegen/generate_contracts.py. DO NOT EDIT.
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ChunkDescriptor {
    pub offset: u64,
    pub byte_length: u32,
    pub sha256: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CASChunkManifest {
    pub root_sha256: String,
    pub total_bytes: u64,
    pub chunk_size: u32,
    pub chunks: Vec<ChunkDescriptor>,
}

impl CASChunkManifest {
    pub fn new(chunk_size: u32) -> Self {
        Self {
            root_sha256: String::new(),
            total_bytes: 0,
            chunk_size,
            chunks: Vec::new(),
        }
    }
}
"""
    os.makedirs(os.path.dirname(RUST_TARGET), exist_ok=True)
    with open(RUST_TARGET, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"[ok] generated {RUST_TARGET}")

if __name__ == "__main__":
    generate_dart()
    generate_rust()
    print("[done] contract generation completed successfully")
